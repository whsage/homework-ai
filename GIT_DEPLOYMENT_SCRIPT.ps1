# ============================================
# 智能作业辅导系统 - Git 部署脚本
# ============================================
# 
# 使用说明：
# 1. 打开一个新的 PowerShell 窗口（重要！）
# 2. 复制下面的命令，一行一行执行
# 3. 遇到问题随时停下来查看提示
#
# ============================================

# ============================================
# 步骤 1：配置 Git 用户信息
# ============================================

# 配置用户名
git config --global user.name "whsage"

# 配置邮箱
git config --global user.email "whsage@qq.com"

# 验证配置（应该显示你刚才设置的信息）
git config --global --list


# ============================================
# 步骤 2：初始化 Git 仓库
# ============================================

# 进入项目目录
cd d:\wenh\AI\homework

# 初始化 Git 仓库
git init

# 查看状态（应该看到很多未跟踪的文件）
git status


# ============================================
# 步骤 3：提交代码到本地仓库
# ============================================

# 添加所有文件到暂存区
git add .

# 提交到本地仓库
git commit -m "Initial commit - 智能作业辅导系统"

# 查看提交历史（应该看到你刚才的提交）
git log --oneline


# ============================================
# 步骤 4：连接 GitHub 远程仓库
# ============================================
#
# ⚠️ 在执行下面的命令之前，你需要：
# 1. 登录 GitHub: https://github.com
# 2. 点击右上角 "+" → "New repository"
# 3. 仓库名填写: homework-ai
# 4. 选择 Public（公开）
# 5. 不要勾选任何选项
# 6. 点击 "Create repository"
# 7. 复制仓库 URL（类似 https://github.com/whsage/homework-ai.git）
#
# ============================================

# 添加远程仓库（⚠️ 替换为你的实际 URL）
git remote add origin https://github.com/whsage/homework-ai.git

# 重命名分支为 main
git branch -M main

# 推送到 GitHub（⚠️ 这时会弹出登录窗口）
git push -u origin main

